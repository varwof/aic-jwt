type Dict = Record<keyof typeof zh, string>;
const dict: Record<Lang, Dict> = { zh: zh as Dict, en };

function detectLang(): Lang {
  // Build-time baked language (two-page build: index.html = en,
  // index.zh.html = zh) takes precedence over ?lang and the browser
  // locale, so each page is stable regardless of the viewer's locale.
  const baked = (globalThis as { __AIC_DEMO_LANG__?: Lang }).__AIC_DEMO_LANG__;
  if (baked === "zh" || baked === "en") return baked;
  if (typeof location !== "undefined") {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "zh" || q === "en") return q;
  }
  if (typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("zh")) {
    return "zh";
  }
  return "en";
}

let lang: Lang = detectLang();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang): void {
  lang = l;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const s = dict[lang][key as keyof typeof zh];
  if (s === undefined) return key;
  if (vars) {
    let out = s;
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
    return out;
  }
  return s;
}
